"""
验证 Claude 全景网页自动更新器的官方来源解析、事件归类、去重、日期边界和监控状态逻辑。
"""

from __future__ import annotations

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULE_PATH = ROOT / "work" / "update-claude-panorama.py"


def load_updater():
    """从 kebab-case 脚本路径加载更新模块。"""
    spec = importlib.util.spec_from_file_location("claude_panorama_updater", MODULE_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError("无法加载自动更新模块")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class AutoUpdateTest(unittest.TestCase):
    """测试不访问网络，使用最小官方页面样本验证核心更新流程。"""

    @classmethod
    def setUpClass(cls) -> None:
        cls.updater = load_updater()

    def test_parse_sitemap_supports_namespace_and_last_modified_date(self) -> None:
        xml = """<?xml version="1.0" encoding="UTF-8"?>
        <urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
          <url><loc>https://www.anthropic.com/news/claude-sonnet-6</loc><lastmod>2026-10-20</lastmod></url>
          <url><loc>https://www.anthropic.com/company</loc></url>
        </urlset>"""
        items = self.updater.parse_sitemap(xml)
        self.assertEqual(items[0], {"url": "https://www.anthropic.com/news/claude-sonnet-6", "lastmod": "2026-10-20"})
        self.assertEqual(items[1]["lastmod"], "")

    def test_parse_page_metadata_prefers_json_ld_publication_date(self) -> None:
        page = """<!doctype html><html><head>
          <title>Introducing Claude Sonnet 6 | Anthropic</title>
          <meta property="og:title" content="Claude Sonnet 6">
          <meta name="description" content="Claude Sonnet 6 improves coding and computer use.">
          <script type="application/ld+json">{"@type":"NewsArticle","datePublished":"2026-10-20T01:00:00Z"}</script>
        </head></html>"""
        metadata = self.updater.parse_page_metadata(page, "https://www.anthropic.com/news/claude-sonnet-6")
        self.assertEqual(metadata["title"], "Claude Sonnet 6")
        self.assertEqual(metadata["description"], "Claude Sonnet 6 improves coding and computer use.")
        self.assertEqual(metadata["date"], "2026-10-20")

    def test_classify_event_uses_specific_product_keywords(self) -> None:
        self.assertEqual(self.updater.classify_event("Claude Code review is generally available"), "智能体/编码")
        self.assertEqual(self.updater.classify_event("Claude Sonnet 6 model"), "模型")
        self.assertEqual(self.updater.classify_event("API pricing update"), "开发者/API")
        self.assertEqual(self.updater.classify_event("Team plan pricing"), "订阅计划")

    def test_make_event_marks_automatic_analysis_and_official_source(self) -> None:
        metadata = {
            "url": "https://www.anthropic.com/news/claude-sonnet-6",
            "title": "Claude Sonnet 6",
            "description": "提升编码与计算机使用能力。",
            "date": "2026-10-20",
        }
        event = self.updater.make_event(metadata, "Anthropic News")
        self.assertEqual(event["category"], "模型")
        self.assertEqual(event["sourceUrl"], metadata["url"])
        self.assertTrue(event["autoGenerated"])
        self.assertEqual(event["verification"], "自动收录")
        self.assertIn("官方", event["significance"])

    def test_merge_events_deduplicates_by_canonical_url_and_respects_cutoff(self) -> None:
        existing = [{"date": "2026-10-15", "title": "旧事件", "sourceUrl": "https://www.anthropic.com/news/old"}]
        candidates = [
            {"date": "2026-10-20", "title": "新事件", "sourceUrl": "https://www.anthropic.com/news/new?utm_source=x"},
            {"date": "2026-10-20", "title": "重复", "sourceUrl": "https://www.anthropic.com/news/old/"},
            {"date": "2026-10-21", "title": "未来事件", "sourceUrl": "https://www.anthropic.com/news/future"},
        ]
        merged, added = self.updater.merge_events(existing, candidates, "2026-10-20")
        self.assertEqual(added, 1)
        self.assertEqual(len(merged), 2)
        self.assertEqual(merged[-1]["title"], "新事件")

    def test_update_files_writes_atomically_and_updates_check_date(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            data_path = root / "timeline.json"
            state_path = root / "state.json"
            data_path.write_text(json.dumps({"cutoff": "2026-10-15", "events": []}), encoding="utf-8")
            state_path.write_text(json.dumps({"knownUrls": [], "pageHashes": {}}), encoding="utf-8")
            self.updater.write_update(
                data_path,
                state_path,
                {"cutoff": "2026-10-20", "lastChecked": "2026-10-20T08:00:00+08:00", "events": []},
                {"knownUrls": ["https://claude.com/new"], "pageHashes": {}},
            )
            saved_data = json.loads(data_path.read_text(encoding="utf-8"))
            saved_state = json.loads(state_path.read_text(encoding="utf-8"))
            self.assertEqual(saved_data["cutoff"], "2026-10-20")
            self.assertEqual(saved_state["knownUrls"], ["https://claude.com/new"])

    def test_source_config_and_pages_workflow_exist(self) -> None:
        config = json.loads((ROOT / "work" / "source-config.json").read_text(encoding="utf-8"))
        self.assertGreaterEqual(len(config["discoverySources"]), 2)
        self.assertGreaterEqual(len(config["monitoredPages"]), 3)
        workflow = (ROOT / ".github" / "workflows" / "update-claude-panorama.yml").read_text(encoding="utf-8")
        self.assertIn("schedule:", workflow)
        self.assertIn("workflow_dispatch:", workflow)
        self.assertIn("deploy-pages", workflow)
        self.assertIn("python3 work/update-claude-panorama.py", workflow)
        self.assertIn("python3 -m unittest discover", workflow)


if __name__ == "__main__":
    unittest.main()
